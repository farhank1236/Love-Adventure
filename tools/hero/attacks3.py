def build_keys():
    out = []
    for name, keys, n in A2M.ATTACKS:
        arms = ARMS[name]
        frames = sorted(set([f for f, _ in keys]) | set(arms))
        kd = {f: dict(ov) for f, ov in keys}
        new = []
        for f in frames:
            ov = {k: v for k, v in kd.get(f, {}).items() if k not in ARM_KEYS}
            if f in arms:
                r, l = arms[f]
                if r is not None:
                    r = dict(r)
                    if r.get('dev') is not None: r['dev'] = WRIST_LOCK + 0.35 * (r['dev'] - WRIST_LOCK)   # stiff wrist
                    ov['R'] = r
                if l is not None: ov['fkL'] = dict(dict(dev=0, flex=10), **l)
            new.append((f, ov))
        out.append((name, new, n))
    return out

